/**
 * GitHub-style formatters. `renderCheckSummary` builds a Markdown body suitable
 * for the GitHub Checks API `output.summary` field or a PR comment.
 * `renderAnnotations` emits GitHub Actions workflow commands (::error /
 * ::warning) that surface findings inline in CI logs.
 *
 * Zero runtime dependencies.
 */

import { Report, Finding, RiskHit } from "./types.js";
import {
  escapePipe,
  ratio,
  minutes,
  verdictMeta,
  severityEmoji,
} from "./util.js";

export function renderCheckSummary(report: Report): string {
  const v = verdictMeta(report.verdict);
  const s = report.summary;

  const lines: string[] = [];
  lines.push(`## PatchSentinel — ${v.emoji} ${v.label}`);
  lines.push("");
  lines.push("| Metric | Value |");
  lines.push("|---|---|");
  lines.push(`| Files changed | ${s.filesChanged} |`);
  lines.push(`| Lines added / removed | +${s.linesAdded} / -${s.linesRemoved} |`);
  lines.push(`| Test-to-code ratio | ${ratio(s.testToCodeRatio)} |`);
  lines.push(`| Risk score | ${s.riskScore} |`);
  lines.push(`| Repetition ratio | ${ratio(s.repetitionRatio)} |`);
  lines.push(`| Sensitive files | ${s.sensitiveFiles} |`);
  lines.push(`| Est. review time | ${minutes(s.reviewMinutes)} |`);

  if (report.findings.length > 0) {
    lines.push("");
    lines.push("### Findings");
    lines.push("");
    for (const f of report.findings) {
      lines.push(`- ${severityEmoji(f.severity)} **${f.title}** — ${f.detail}`);
    }
  }

  if (report.risks.length > 0) {
    lines.push("");
    lines.push("### Risk signals");
    lines.push("");
    lines.push("| Pattern | Weight | Count | Path | Detail |");
    lines.push("|---|---|---|---|---|");
    for (const r of report.risks) {
      lines.push(
        `| \`${r.patternId}\` | ${r.weight} | ${r.count} | \`${r.path}\` | ${escapePipe(r.message)} |`,
      );
    }
  }

  lines.push("");
  lines.push(
    "<sub>Generated by PatchSentinel — deterministic AI contribution quality gate.</sub>",
  );
  return lines.join("\n") + "\n";
}

export function renderAnnotations(report: Report): string {
  const lines: string[] = [];
  for (const f of report.findings) {
    const level = annotationLevel(f);
    // Escape per GitHub workflow-command rules (%, \r, \n).
    lines.push(`::${level} title=${encodeProp(f.title)}::${encodeData(f.detail)}`);
  }
  return lines.join("\n") + (lines.length > 0 ? "\n" : "");
}

function annotationLevel(f: Finding): "error" | "warning" | "notice" {
  switch (f.severity) {
    case "error":
      return "error";
    case "warn":
      return "warning";
    default:
      return "notice";
  }
}

function encodeData(s: string): string {
  return s.replace(/%/g, "%25").replace(/\r/g, "%0D").replace(/\n/g, "%0A");
}

function encodeProp(s: string): string {
  return encodeData(s).replace(/:/g, "%3A").replace(/,/g, "%2C");
}

/** Convenience helper returning both artifacts at once. */
export function renderGitHub(report: Report): { summary: string; annotations: string } {
  return {
    summary: renderCheckSummary(report),
    annotations: renderAnnotations(report),
  };
}

